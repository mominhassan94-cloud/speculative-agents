"""Build working_piece.md and status_update.pdf from the raw run logs in logs/.

Every model output and number in both files is read from the logs written by
`demo.py --log-dir` and `spec_demo.py`; nothing is typed in by hand.

  pip install -r reports/status_update/requirements.txt
  python reports/status_update/make_diagram.py
  python reports/status_update/build_report.py
"""
import glob
import json
import os
import re

HERE = os.path.dirname(os.path.abspath(__file__))
LOGS = os.path.join(HERE, "logs")


def latest(pattern):
    files = sorted(glob.glob(os.path.join(LOGS, pattern)))
    if not files:
        raise SystemExit(f"no log matching {pattern}")
    return files[-1]


def rel(p):
    return os.path.relpath(p, HERE)


LLM_JSON = latest("demo-llm-[0-9]*.json")
RULES_JSON = latest("demo-rules-[0-9]*.json")
SPEC_TXT = latest("spec_demo-*.txt")
RETRY_TXT = sorted(glob.glob(os.path.join(LOGS, "pre-fix", "demo-llm-rules-*.txt")))
llm = json.load(open(LLM_JSON))
rules = json.load(open(RULES_JSON))

spec_txt = open(SPEC_TXT).read()
sections = dict(re.findall(r"=== (.+?) ===\n(.*?)(?=\n\n=== |\Z)", spec_txt, re.S))
SPEC_MODEL = sections["MODEL"].strip()
SPEC_SYSTEM = sections["PROMPT (system)"].strip()
SPEC_INPUT = sections["INPUT (user message sent to the model)"].strip()
SPEC_RAW = sections["MODEL'S RAW OUTPUT"].strip()
SPEC_GUESS = sections["PARSED GUESS"].strip()

retry_note = None
for f in RETRY_TXT:
    m = re.search(r"rate-limit retries: (\d+) \(([\d.]+)s", open(f).read())
    if m and int(m.group(1)) > 0:
        retry_note = (int(m.group(1)), float(m.group(2)), rel(f))


def fmt_call(fc):
    return f"{fc['name']}({json.dumps(fc['args'])})"


def turn_lines(turns):
    out = []
    for i, t in enumerate(turns, 1):
        calls = [p["function_call"] for p in t["parts"] if "function_call" in p]
        texts = [p["text"] for p in t["parts"] if "text" in p]
        if calls:
            out.append(f"turn {i} ({t['llm_s']:.2f}s): function_call " + " + ".join(fmt_call(c) for c in calls))
        else:
            out.append(f"turn {i} ({t['llm_s']:.2f}s): text, {len(texts[0]) if texts else 0} chars (final answer)")
    return out


def final_text(turns):
    return next(p["text"] for p in turns[-1]["parts"] if "text" in p)


def row(name, d):
    b, s = d["baseline"], d["speculative"]
    sm = s["summary"]
    r = d.get("rate_limit_retries", {"count": 0})
    return [name, f"{b['total_s']:.1f}", f"{s['total_s']:.1f}", f"{(1 - s['total_s'] / b['total_s']) * 100:.0f}%",
            str(sm["speculative_calls"]), f"{sm['hits']}/{len(s['calls']) - 1}", str(sm["wasted"]),
            str(sm["too_late"]), f"{sm['est_seconds_saved']:.2f}", str(r["count"]),
            "yes" if b["calls"] == s["calls"] else "no"]


HEADER = ["Speculator", "Baseline s", "Spec. s", "Faster", "Launched", "Hits", "Wasted", "Too late",
          "Tool s saved", "429s", "Same calls"]
ROWS = [row(f"LLM ({llm['speculator_model']})", llm), row("Rules", rules)]

# ------------------------------------------------------------------------------------------------
# working_piece.md: full verbatim record
# ------------------------------------------------------------------------------------------------
md = []
w = md.append
w("# One working piece: real runs with Gemini\n")
w("Everything below is copied verbatim from the raw logs (generated by the code on branch "
  "`khizar/gemini-migration`). Nothing is edited; long tool lists are shown in full.\n")
w("Raw logs:\n")
for p in (SPEC_TXT, LLM_JSON, RULES_JSON):
    w(f"- `{rel(p)}`")
for p in sorted(glob.glob(os.path.join(LOGS, "demo-llm-*.txt"))):
    w(f"- `{rel(p)}` (console output)")
w("")
w("## 1. Speculator alone (`python spec_demo.py`)\n")
w(f"Model: `{SPEC_MODEL}`\n")
w("### Prompt (system instruction)\n```\n" + SPEC_SYSTEM + "\n```\n")
w("### Input (user message sent to the model)\n```\n" + SPEC_INPUT + "\n```\n")
w("### Raw model output\n```\n" + SPEC_RAW + "\n```\n")
w("### Parsed guess\n```\n" + SPEC_GUESS + "\n```\n")
w("This guess matches the agent's real next call in the end-to-end runs below (`get_fare_details` for UA482).\n")

for title, d, cmd in (("2. End-to-end: Gemini agent + Gemini (LLM) speculator", llm, "python demo.py --llm"),
                      ("3. End-to-end: Gemini agent + rule-based speculator", rules,
                       "python demo.py --llm --speculator rules")):
    w(f"## {title} (`{cmd}`)\n")
    w(f"Agent model: `{d['agent']}`. Speculator: `{d['speculator']}`"
      + (f" (`{d['speculator_model']}`)" if d["speculator_model"] else "") + ".\n")
    w("Task (user message to the agent; the 9 mock tools are passed as Gemini function declarations):\n")
    w("```\n" + d["task"] + "\n```\n")
    for k in ("baseline", "speculative"):
        r = d[k]
        w(f"### {k.capitalize()} run: {r['total_s']:.2f}s total\n")
        w("Model turns (each line is one Gemini call; every function call the model requested is listed):\n")
        w("```\n" + "\n".join(turn_lines(r["model_turns"])) + "\n```\n")
        w("Final answer (raw model text):\n")
        w("```\n" + final_text(r["model_turns"]) + "\n```\n")
    s = d["speculative"]
    if s.get("speculator_calls"):
        w("### Speculator calls during the speculative run (raw output, latency)\n")
        w("```\n" + "\n".join(f"{c['spec_s']:.2f}s  {c['raw_output']}" for c in s["speculator_calls"]) + "\n```\n")
    w("### Speculation log\n```\n" + "\n".join(s["speculation_log"]) + "\n```\n")
    w("### Summary\n```\n" + json.dumps(s["summary"]) + f"\nrate-limit retries: {d['rate_limit_retries']}\n```\n")

w("## 4. Numbers at a glance\n")
w("| " + " | ".join(HEADER) + " |")
w("|" + "---|" * len(HEADER))
for r in ROWS:
    w("| " + " | ".join(r) + " |")
w("")
w("Notes:\n")
w("- One run per configuration (n=1). Gemini latency varies by a few tenths of a second per call, "
  "so small differences are within noise.")
w("- *Hits* = correct guesses out of the calls that could be speculated (every call after the first). "
  "*Too late* = the guess arrived after the agent had already made that call, so it was dropped instead of run. "
  "*Wasted* = speculative tool runs whose result was never used.")
w("- *Tool s saved* is the runtime's own estimate (tool time minus time spent waiting on the hit); "
  "end-to-end differences also include Gemini latency variation.")
w("- The final answers are worded differently between runs (Gemini sampling), but the tool-call sequence and the "
  "cost figures they report are the same.")
w("- Gemini requested several `get_fare_details` calls in a single turn (parallel function calling). The agent loop "
  "runs one tool per step, so it executes the first call and the model asks again for the rest next turn.")
if retry_note:
    w(f"- 429 handling was exercised in an earlier run (`{retry_note[2]}`): {retry_note[0]} rate-limit retries, "
      f"{retry_note[1]:.1f}s of backoff, after which the run completed. That run is excluded from the timing "
      "numbers because the backoff inflated its baseline.")
open(os.path.join(HERE, "working_piece.md"), "w").write("\n".join(md) + "\n")
print("wrote working_piece.md")

