def esc(s):
    return s.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")


def trim_input(s):
    """Trim the speculator input for the PDF: drop the tool list, shown as an explicit marker."""
    a, b = s.index("TOOLS:"), s.index("CALLS SO FAR:")
    return s[:a] + "TOOLS: [9 tool descriptions omitted; full text in working_piece.md]\n\n" + s[b:]


def wrap(s, n=128):
    out = []
    for line in s.split("\n"):
        while len(line) > n:
            out.append(line[:n])
            line = "    " + line[n:]
        out.append(line)
    return "\n".join(out)


